import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';
import { defineConfig, globalIgnores } from 'eslint/config';
import obsidianmd from 'eslint-plugin-obsidianmd';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Mirrors the Obsidian community-plugin scanner: `obsidianmd.configs.recommended`
// (ESLint core + typescript-eslint type-checked + Obsidian rules) across every
// tree the scanner reads — src/ (the shipped bundle), infrastructure/ (CDK
// stacks synthesized into src/infrastructure/templates.ts) and e2e/ (the
// Playwright harness; the recommended config already relaxes the
// Obsidian-runtime rules for e2e/ as test code). `npm run lint` should therefore
// surface the same findings the review does.
//
// Each tree type-checks against its own tsconfig. Locally infrastructure/ has
// its own node_modules (aws-cdk-lib), so its CDK types resolve here even though
// they don't in the scanner's root-only install.
export default defineConfig([
	globalIgnores([
		'node_modules',
		'**/node_modules',
		'main.js',
		'esbuild.config.mjs',
		'version-bump.mjs',
		'eslint.config.mjs',
		'private',
		'templates',
		'specs',
		'docs',
		'e2e/test-vault',
		'e2e/test-user-data',
		'e2e/results',
		'e2e/dist',
		'infrastructure/cdk.out',
		'infrastructure/assets',
		// Excluded by the community scanner as tests / utility scripts.
		'**/scripts/**',
		'**/tests/**',
		'**/*.{test,spec}.*',
		// Generated by `npm run synth:site` / `npm run synth`.
		'src/publish/siteAssets.ts',
		'src/infrastructure/templates.ts',
	]),
	...obsidianmd.configs.recommended,
	{
		files: ['src/**/*.ts', 'custom.d.ts'],
		languageOptions: {
			parserOptions: { project: './tsconfig.json', tsconfigRootDir: __dirname },
		},
		rules: {
			// Stricter than recommended: src/ has been swept clean of `any`, so the
			// whole unsafe family is an error to keep the shipped bundle at that bar.
			'@typescript-eslint/no-explicit-any': 'error',
			'@typescript-eslint/no-floating-promises': 'error',
			'@typescript-eslint/no-misused-promises': 'error',
			'@typescript-eslint/no-unsafe-assignment': 'error',
			'@typescript-eslint/no-unsafe-member-access': 'error',
			'@typescript-eslint/no-unsafe-call': 'error',
			'@typescript-eslint/no-unsafe-return': 'error',
			'@typescript-eslint/no-unsafe-argument': 'error',
		},
	},
	{
		// The community scanner doesn't report these (none of the 0.8.0 review's
		// findings came from them). src/ deliberately uses `String(value)` /
		// template interpolation on untyped frontmatter values, so leave them off
		// to keep `npm run lint` aligned with what the review actually checks.
		files: ['**/*.ts'],
		rules: {
			'@typescript-eslint/no-base-to-string': 'off',
			'@typescript-eslint/restrict-template-expressions': 'off',
		},
	},
	{
		files: ['e2e/**/*.ts'],
		languageOptions: {
			parserOptions: { project: './e2e/tsconfig.json', tsconfigRootDir: __dirname },
		},
	},
	{
		files: ['infrastructure/**/*.ts'],
		languageOptions: {
			parserOptions: { project: './infrastructure/tsconfig.json', tsconfigRootDir: __dirname },
		},
	},
]);
